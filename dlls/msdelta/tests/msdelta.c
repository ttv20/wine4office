static void test_apply_delta(void)
{
    static const BYTE pa30[] = {'P','A','3','0'};
    DELTA_INPUT source = {{NULL}, 0, FALSE};
    DELTA_INPUT delta = {{pa19_patch}, sizeof(pa19_patch), FALSE};
    DELTA_OUTPUT output;
    BOOL ret;

    SetLastError(0xdeadbeef);
    ret = ApplyDeltaB(DELTA_APPLY_FLAG_ALLOW_PA19, source, delta, NULL);
    ok(!ret && GetLastError() == ERROR_INVALID_PARAMETER,
       "expected ERROR_INVALID_PARAMETER, got %lu\n", GetLastError());

    output.lpStart = (void *)0xdeadbeef;
    output.uSize = 0xdeadbeef;
    source.uSize = 1;
    SetLastError(0xdeadbeef);
    ret = ApplyDeltaB(DELTA_APPLY_FLAG_ALLOW_PA19, source, delta, &output);
    ok(!ret && GetLastError() == ERROR_INVALID_PARAMETER,
       "expected ERROR_INVALID_PARAMETER, got %lu\n", GetLastError());
    ok(!output.lpStart && !output.uSize, "unexpected output %p/%Iu\n", output.lpStart, output.uSize);
    source.uSize = 0;

    delta.lpStart = (void *)pa30;
    delta.uSize = sizeof(pa30);
    SetLastError(0xdeadbeef);
    ret = ApplyDeltaB(DELTA_APPLY_FLAG_ALLOW_PA19, source, delta, &output);
    ok(!ret && GetLastError() == ERROR_PATCH_PACKAGE_UNSUPPORTED,
       "expected ERROR_PATCH_PACKAGE_UNSUPPORTED, got %lu\n", GetLastError());

    delta.lpStart = (void *)pa19_patch;
    delta.uSize = sizeof(pa19_patch);
    SetLastError(0xdeadbeef);
    ret = ApplyDeltaB(DELTA_FLAG_NONE, source, delta, &output);
    ok(!ret && GetLastError() == ERROR_PATCH_PACKAGE_UNSUPPORTED,
       "expected ERROR_PATCH_PACKAGE_UNSUPPORTED, got %lu\n", GetLastError());

    ret = ApplyDeltaB(DELTA_APPLY_FLAG_ALLOW_PA19, source, delta, &output);
    ok(ret, "ApplyDeltaB failed: %lu\n", GetLastError());
    if (ret)
    {
        ok(output.uSize == sizeof(expected), "unexpected output size %Iu\n", output.uSize);
        ok(!memcmp(output.lpStart, expected, sizeof(expected)), "unexpected output data\n");
        ok(DeltaFree(output.lpStart), "DeltaFree failed: %lu\n", GetLastError());
    }
}

START_TEST(msdelta)
{
    test_apply_delta();
}
